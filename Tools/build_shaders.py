"""Compiles src/shaders/*.frag.hlsl to DXIL with the Windows SDK's dxc and writes src/shaders/<name>.dxil.h
(committed, so a normal build doesn't need dxc). Only DXIL: the SDK's dxc has no SPIR-V output, so the CRT shader
runs on the D3D12 GPU renderer (on Linux / Steam Deck under Proton that's vkd3d).
usage: build_shaders.py [path to dxc.exe]"""
import glob
import os
import subprocess
import sys

ROOT = os.path.join(os.path.dirname(__file__), '..')


def find_dxc():
    if len(sys.argv) > 1:
        return sys.argv[1]
    kits = r'C:\Program Files (x86)\Windows Kits\10\bin'
    found = sorted(glob.glob(os.path.join(kits, '10.*', 'x64', 'dxc.exe')))
    if not found:
        sys.exit('dxc.exe not found (install the Windows SDK or pass its path)')
    return found[-1]


def main():
    dxc = find_dxc()
    for hlsl in sorted(glob.glob(os.path.join(ROOT, 'src', 'shaders', '*.frag.hlsl'))):
        name = os.path.basename(hlsl)[:-len('.frag.hlsl')]
        out = hlsl[:-len('.hlsl')] + '.dxil'
        subprocess.run([dxc, '-T', 'ps_6_0', '-E', 'main', '-O3', '-Fo', out, hlsl], check=True)
        data = open(out, 'rb').read()
        os.remove(out)
        with open(os.path.join(ROOT, 'src', 'shaders', name + '.dxil.h'), 'w') as f:
            f.write('// Generated by Tools/build_shaders.py from %s.frag.hlsl. Do not edit.\n' % name)
            f.write('static const unsigned char k_%s_dxil[] = {\n' % name)
            for k in range(0, len(data), 20):
                f.write('  ' + ', '.join('0x%02x' % b for b in data[k:k + 20]) + ',\n')
            f.write('};\n')
        print(name, len(data), 'bytes')


if __name__ == '__main__':
    main()
